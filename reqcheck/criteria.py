def describe(criteria: tuple[Criterion, ...]) -> str:
    """Текстовое описание критериев для промпта."""
    lines = []
    for c in criteria:
        lines.append(
            f"- {c.code} — {c.name} ({c.source}). {c.definition} "
            f"Типичные дефекты: {c.defect_examples}."
        )
    return "\n".join(lines)
